using System;
using System.Collections.Generic;
using System.IO;
using System.Text;

namespace GameJson
{
    internal static class ConfigCodeWriter
    {
        public static string Generate(ConfigDocument document, string namespaceName, string className)
        {
            Identifier(className);
            if (string.IsNullOrEmpty(namespaceName)) throw new ArgumentException("A namespace is required.");
            var ns = namespaceName.Split('.');
            for (int i = 0; i < ns.Length; i++) { Identifier(ns[i]); ns[i] = "@" + ns[i]; }
            var source = SourceDocument.Create(document);
            ValidateSymbols(source, className);
            var b = new StringBuilder();
            Line(b, "// <auto-generated />");
            Line(b, "// Read-only snapshot views. Regenerate when the required configuration contract changes.");
            Line(b, "namespace " + string.Join(".", ns)); Line(b, "{");
            Line(b, "    public sealed class @" + className); Line(b, "    {");
            Line(b, "        public int Version { get; }");
            foreach (var t in source.Tables) Line(b, "        public @" + Name(t.Name) + "Table @" + Name(t.Name) + " { get; }");
            Line(b, "        public @" + className + "(global::GameJson.IConfigData data)"); Line(b, "        {");
            Line(b, "            if (data == null) throw new global::System.ArgumentNullException(nameof(data));");
            Line(b, "            Version = data.Version;");
            foreach (var t in source.Tables) Line(b, "            @" + Name(t.Name) + " = new @" + Name(t.Name) + "Table(this, data.Table(\"" + t.Name + "\"));");
            foreach (var t in source.Tables) foreach (var f in t.Fields) if (f.Reference != null)
                Line(b, "            global::GameJson.ConfigContract.RequireReference(data, \"" + t.Name + "\", \"" + f.Name + "\", \"" + f.Reference + "\");");
            Line(b, "            ValidateReferences();"); Line(b, "        }");
            Line(b, "        void ValidateReferences()"); Line(b, "        {");
            foreach (var t in source.Tables) foreach (var f in t.Fields) if (f.Reference != null)
            {
                string p = Name(f.Name), target = Name(f.Reference);
                Line(b, "            foreach (@" + Name(t.Name) + "Row row in @" + Name(t.Name) + ")"); Line(b, "            {");
                if (f.Kind == FieldKind.IntList) Line(b, "                foreach (int id in row.@" + p + ")");
                else Line(b, "                int id = row.@" + p + ";");
                Line(b, "                if (!@" + target + ".TryGet(id, out _)) throw new global::System.IO.InvalidDataException(\"" + t.Name + "[\" + row.Id + \"]." + f.Name + ": missing " + f.Reference + "[\" + id + \"]\");");
                Line(b, "            }");
            }
            Line(b, "        }");
            foreach (var t in source.Tables) EmitTable(b, t, className);
            Line(b, "    }"); Line(b, "}"); return b.ToString();
        }
        static void EmitTable(StringBuilder b, SourceTable table, string owner)
        {
            string n = Name(table.Name), tableType = "@" + n + "Table", rowType = "@" + n + "Row";
            Line(b, "        public sealed class " + tableType); Line(b, "        {");
            Line(b, "            internal readonly @" + owner + " Owner;");
            Line(b, "            readonly global::GameJson.IConfigTable data;");
            foreach (var f in table.Fields) Line(b, "            internal readonly global::GameJson." + ColumnType(f.Kind) + " C" + f.Index + ";");
            Line(b, "            internal " + tableType + "(@" + owner + " owner, global::GameJson.IConfigTable data)"); Line(b, "            {");
            Line(b, "                Owner = owner; this.data = data; Count = data.Count;");
            Line(b, "                try {");
            foreach (var f in table.Fields) Line(b, "                    C" + f.Index + " = global::GameJson.ConfigColumns." + Binding(f.Kind) + "(data, \"" + f.Name + "\");");
            Line(b, "                } catch (global::System.Exception e) { throw new global::System.IO.InvalidDataException(\"Binding " + table.Name + ": \" + e.Message, e); }");
            Line(b, "            }");
            Line(b, "            public int Count { get; }");
            foreach (var f in table.Fields) Line(b, "            public global::GameJson." + ColumnType(f.Kind) + " @" + Name(f.Name) + "Column => C" + f.Index + ";");
            Inline(b);
            Line(b, "            public " + rowType + " At(int index)"); Line(b, "            {");
            Line(b, "                if ((uint)index >= (uint)Count) throw new global::System.ArgumentOutOfRangeException(nameof(index));");
            Line(b, "                return new " + rowType + "(this, index);"); Line(b, "            }");
            Inline(b); Line(b, "            public bool TryGet(int id, out " + rowType + " value)"); Line(b, "            {");
            Line(b, "                int index = data.Find(id);");
            Line(b, "                if ((uint)index >= (uint)Count) { value = default; return false; }");
            Line(b, "                value = new " + rowType + "(this, index); return true;"); Line(b, "            }");
            Inline(b); Line(b, "            public " + rowType + " Get(int id)"); Line(b, "            {");
            Line(b, "                if (TryGet(id, out " + rowType + " value)) return value;");
            Line(b, "                throw new global::System.Collections.Generic.KeyNotFoundException(\"" + table.Name + "[\" + id + \"]\");"); Line(b, "            }");
            Line(b, "            public Enumerator GetEnumerator() => new Enumerator(this);");
            Line(b, "            public struct Enumerator"); Line(b, "            {");
            Line(b, "                readonly " + tableType + " table; int index;");
            Line(b, "                internal Enumerator(" + tableType + " table) { this.table = table; index = -1; }");
            Line(b, "                public " + rowType + " Current { " + InlineAttribute + " get => table.At(index); }");
            Inline(b);
            Line(b, "                public bool MoveNext() { if (index < table.Count) index++; return index < table.Count; }");
            Line(b, "            }"); Line(b, "        }");
            Line(b, "        public readonly struct " + rowType); Line(b, "        {");
            Line(b, "            readonly " + tableType + " table; readonly int index;");
            Line(b, "            internal " + rowType + "(" + tableType + " table, int index) { this.table = table; this.index = index; }");
            Line(b, "            public bool IsValid => table != null;");
            Inline(b); Line(b, "            void EnsureValid() { if (table == null) throw new global::System.InvalidOperationException(\"Invalid " + n + " row. Check TryGet before reading.\"); }");
            foreach (var f in table.Fields)
            {
                string p = Name(f.Name);
                Line(b, "            public " + ValueType(f.Kind) + " @" + p + " { " + InlineAttribute + " get { EnsureValid(); return table.C" + f.Index + "[index]; } }");
                if (f.Reference == null) continue;
                string target = Name(f.Reference);
                if (f.Kind == FieldKind.Int)
                    Line(b, "            public @" + target + "Row @" + p + "Record { get { EnsureValid(); return table.Owner.@" + target + ".Get(@" + p + "); } }");
                else
                    Line(b, "            public @" + target + "Row @Resolve" + p + "(int itemIndex) { EnsureValid(); return table.Owner.@" + target + ".Get(@" + p + "[itemIndex]); }");
            }
            Line(b, "        }");
        }
        static void ValidateSymbols(SourceDocument source, string className)
        {
            var root = new HashSet<string>(StringComparer.Ordinal) { "Version", "ValidateReferences" };
            Add(root, className, className);
            foreach (var t in source.Tables)
            {
                string n = Name(t.Name);
                Add(root, n, t.Name); Add(root, n + "Table", t.Name); Add(root, n + "Row", t.Name);
                var columns = new HashSet<string>(StringComparer.Ordinal) { "Owner", "data", "Count", "At", "TryGet", "Get", "GetEnumerator", "Enumerator", n + "Table" };
                var members = new HashSet<string>(StringComparer.Ordinal) { "IsValid", "EnsureValid", "table", "index", n + "Row" };
                foreach (var f in t.Fields)
                {
                    string p = Name(f.Name); Add(members, p, t.Name + "." + f.Name);
                    Add(columns, p + "Column", t.Name + "." + f.Name);
                    if (f.Reference != null) Add(members, f.Kind == FieldKind.Int ? p + "Record" : "Resolve" + p, t.Name + "." + f.Name);
                }
            }
        }
        static void Add(HashSet<string> names, string name, string location)
        { if (!names.Add(name)) throw new InvalidDataException(location + ": generated C# symbol collision: " + name); }
        static string Name(string value) { Identifier(value); return char.ToUpperInvariant(value[0]) + value.Substring(1); }
        static void Identifier(string value)
        {
            if (string.IsNullOrEmpty(value)) throw new ArgumentException("Empty C# identifier.");
            for (int i = 0; i < value.Length; i++) {
                char c = value[i]; bool valid = c == '_' || c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || i > 0 && c >= '0' && c <= '9';
                if (!valid) throw new ArgumentException("C# generation requires ASCII identifiers: " + value);
            }
        }
        static string ColumnType(FieldKind kind) => kind == FieldKind.IntList ? "IntListColumn" : kind.ToString() + "Column";
        const string InlineAttribute = "[global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]";
        static void Inline(StringBuilder builder) => Line(builder, "            " + InlineAttribute);
        static string Binding(FieldKind kind) => kind == FieldKind.IntList ? "List" : kind.ToString();
        static string ValueType(FieldKind kind)
        {
            switch (kind) {
                case FieldKind.Int: return "int";
                case FieldKind.String: return "string";
                case FieldKind.IntList: return "global::GameJson.IntList";
                case FieldKind.Long: return "long";
                case FieldKind.Float: return "float";
                case FieldKind.Bool: return "bool";
                default: throw new ArgumentOutOfRangeException(nameof(kind));
            }
        }
        static void Line(StringBuilder builder, string value) { builder.Append(value); builder.Append('\n'); }
    }
}
